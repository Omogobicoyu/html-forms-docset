<!DOCTYPE html>
<!-- ОБЩАЯ ШАПКА СТРАНИЦ. DOCTYPE сообщает браузеру, что используется HTML5.
     lang="ru" задаёт русский язык документа. -->
<html lang="ru">
<head>
    <!-- UTF-8 позволяет правильно показывать русские буквы. -->
    <meta charset="UTF-8">
    <!-- На телефоне ширина страницы соответствует ширине экрана, масштаб изначально 1. -->
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <!-- title — название вкладки. $title задаёт подключающая этот файл PHP-страница.
         e() подготавливает значение для вывода в HTML. -->
    <title><?= e($title) ?> — Конференции.РФ</title>
    <!-- Bootstrap — готовые классы для полей, кнопок, отступов и расположения блоков.
         Файл лежит рядом с сайтом и загружается без интернета. -->
    <link rel="stylesheet" href="bootstrap.min.css">
    <!-- Собственные цвета, шрифты и размеры. Более поздние правила имеют приоритет
         при равной специфичности и важности остальных условий CSS. -->
    <link rel="stylesheet" href="style.css">
</head>
<!-- На входе и регистрации $auth_page = true: добавляем класс для центрирования.
     На остальных страницах переменной нет, поэтому класс остаётся пустым. -->
<body class="<?= !empty($auth_page) ? 'auth-page' : '' ?>">
<!-- body — видимая часть документа, main — его основное содержимое.
     container ограничивает ширину, py-4 добавляет отступы сверху и снизу. -->
<main class="container py-4">
    <!-- h1 — главный заголовок сайта. h2 ниже содержит название текущей страницы. -->
    <h1>Конференции.РФ</h1>
    <!-- Меню есть только при наличии user_id в сессии, то есть после входа.
         if (...): открывает условие, endif; его закрывает. -->
    <?php if (isset($_SESSION['user_id'])): ?>
        <!-- nav объединяет ссылки навигации. my-3 — отступы по вертикали,
             d-flex — расположение в ряд, gap-3 — промежутки, flex-wrap — перенос строк. -->
        <nav class="my-3 d-flex gap-3 flex-wrap">
            <!-- Роль определяет набор ссылок. Сами страницы также проверяют доступ в PHP. -->
            <?php if ($_SESSION['role'] === 'admin'): ?>
                <a href="admin.php">Панель администратора</a>
            <?php else: ?>
                <a href="requests.php">Мои заявки</a>
                <a href="create.php">Создать заявку</a>
            <?php endif; ?>
            <!-- Ссылка выхода доступна любой роли и ведёт на очистку сессии. -->
            <a href="logout.php">Выйти</a>
        </nav>
    <?php endif; ?>
    <!-- Одна переменная $title используется и в названии вкладки, и в заголовке. -->
    <h2 class="my-3"><?= e($title) ?></h2>
    <!-- empty проверяет пустоту. !empty — сообщение есть, значит нужно его показать.
         alert alert-danger оформляет ошибку; role="alert" обозначает важное сообщение. -->
    <?php if (!empty($error)): ?>
        <p class="alert alert-danger" role="alert"><?= e($error) ?></p>
    <?php endif; ?>
<!-- Здесь подключающая страница продолжает main своей формой или списком заявок.
     Закрывающие теги main, body и html находятся в footer.php. -->
