<?php
// ОБЩИЙ ФАЙЛ: подключение к базе, запуск сессии и вспомогательные функции.
// Другие страницы подключают его командой require 'db.php'.
// PHP-код выполняется на сервере. Браузер получает только готовый HTML.

// class описывает класс — здесь он объединяет код подключения к MySQL.
// PDO — встроенный в PHP интерфейс для работы с базами данных.
class Database
{
    // public: метод доступен снаружи класса. connect — придуманное имя метода.
    public function connect()
    {
        // new PDO создаёт подключение, а return возвращает его вызывающему коду.
        // mysql — тип БД; host — адрес сервера MySQL; dbname — имя базы;
        // charset=utf8mb4 позволяет правильно хранить русский текст.
        // 'root' — пользователь MySQL, '' — его пароль (здесь пустая строка).
        // Базу conferences заранее создают через интерфейс phpMyAdmin в Open Server.
        // phpMyAdmin управляет базой, а PHP подключается непосредственно к MySQL.
        return new PDO('mysql:host=127.0.0.1;dbname=conferences;charset=utf8mb4', 'root', '', [
            // Ошибка SQL вызовет исключение: PHP сообщит об ошибке запроса.
            PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
            // Строки результата будут массивами с именами столбцов: $user['login'].
            PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            // Подготовленные запросы обрабатывает MySQL, а не эмуляция в PHP.
            PDO::ATTR_EMULATE_PREPARES => false
        ]);
    }
}

// Сессия хранит данные о вошедшем пользователе между открытиями страниц.
// session_start открывает существующую сессию или начинает новую.
// Её запускают до вывода HTML, поскольку PHP может отправлять cookie браузеру.
session_start();
// new Database() создаёт объект; ->connect() вызывает его метод.
// Переменная $db содержит подключение: через неё выполняются SQL-запросы.
$db = (new Database())->connect();

// Короткая функция e() подготавливает текст для безопасного вывода в HTML.
// Например, введённое <script> отобразится как текст, а не как HTML-тег.
// Это обработка вывода в страницу. Параметры SQL передаются отдельно через execute().
function e($text)
{
    // (string) приводит значение к строке; ENT_QUOTES обрабатывает оба вида кавычек.
    // htmlspecialchars заменяет специальные символы HTML, UTF-8 задаёт кодировку.
    return htmlspecialchars((string)$text, ENT_QUOTES, 'UTF-8');
}

// Эту функцию вызывают в начале страниц, доступных только после входа.
function require_login()
{
    // isset проверяет наличие значения; ! означает «не».
    // Если в сессии нет user_id, пользователь ещё не вошёл.
    if (!isset($_SESSION['user_id'])) {
        // Location отправляет браузеру команду перейти на страницу авторизации.
        // header нужно вызывать до вывода HTML или другого текста.
        header('Location: index.php');
        // exit прекращает выполнение: закрытая часть страницы не откроется.
        exit;
    }
}
